-- 이 시범 버전은 닉네임과 음악 취향을 참여자끼리 공개하는 구조입니다.
-- 실명/연락처/비밀번호 등 개인정보를 저장하지 마세요.

create table if not exists public.submissions (
    id bigint generated by default as identity primary key,
    nickname text not null unique check (char_length(nickname) between 2 and 20),
    song_ids text[] not null check (cardinality(song_ids) between 5 and 15),
    genres text[] not null default '{}',
    moods text[] not null default '{}',
    created_at timestamptz not null default now()
);

alter table public.submissions enable row level security;

-- 시범 프로젝트: 비로그인 참여자가 설문을 제출하고 전체 매칭 결과를 읽을 수 있게 합니다.
-- 운영용 서비스로 공개하기 전에는 Supabase Auth와 더 제한적인 정책을 추가하세요.
revoke all on table public.submissions from anon, authenticated;
grant select, insert on table public.submissions to anon;

drop policy if exists "demo_read_submissions" on public.submissions;
create policy "demo_read_submissions"
on public.submissions for select to anon
using (true);

drop policy if exists "demo_insert_submissions" on public.submissions;
create policy "demo_insert_submissions"
on public.submissions for insert to anon
with check (
    char_length(nickname) between 2 and 20
    and cardinality(song_ids) between 5 and 15
);
